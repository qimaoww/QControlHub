//go:build ignore

// Generate browser defaults and contract choices from the Go authority.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/qimaoww/qcontrolhub/internal/core"
)

func main() {
	defaults := core.DefaultPanelSettings()
	values := []struct {
		name  string
		value any
	}{
		{"panelDefaults", map[string]int{"task_page_size": defaults.TaskPageSize, "task_poll_interval_ms": defaults.TaskPollIntervalMS, "ui_font_scale": defaults.UIFontScale}},
		{"panelSettingOptions", core.PanelSettingOptions()},
		{"allEngines", core.AllEngines()},
		{"taskFilterActions", core.TaskFilterActions()},
	}
	content := "// Generated by go run scripts/generate-runtime-defaults.go; do not edit.\n"
	for _, item := range values {
		encoded, err := json.Marshal(item.value)
		if err != nil {
			panic(err)
		}
		content += fmt.Sprintf("export const %s = Object.freeze(%s);\n", item.name, encoded)
	}
	engines := []string{}
	for _, engine := range core.AllEngines() {
		engines = append(engines, string(engine))
	}
	shell := "# Generated by go run scripts/generate-runtime-defaults.go; do not edit.\nqch_default_agent_engines='" + strings.Join(engines, ",") + "'\n"
	if err := os.WriteFile("deploy/modules/shared/default-engines.sh", []byte(shell), 0644); err != nil {
		panic(err)
	}
	if err := os.WriteFile("frontend/modules/runtime-defaults.js", []byte(content), 0644); err != nil {
		panic(err)
	}
}
