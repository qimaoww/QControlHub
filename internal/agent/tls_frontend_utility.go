package agent

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"time"

	"github.com/qimaoww/qcontrolhub/internal/core"
)

type tlsFrontendRequest struct {
	Service   string             `json:"service"`
	Kind      string             `json:"kind"`
	Action    core.Action        `json:"action"`
	Stage     bool               `json:"stage"`
	Frontends []core.TLSFrontend `json:"frontends"`
}

var tlsRequestName = regexp.MustCompile(`^[a-f0-9]{24}\.json$`)

// RunTLSFrontendRequest is a fixed local helper. Request files are root-owned,
// private, and generated by the Agent; service identities are restricted to
// the panel's standard sing-box base service and shared instances.
func RunTLSFrontendRequest(ctx context.Context, name string) error {
	if !tlsRequestName.MatchString(name) {
		return errors.New("invalid TLS request name")
	}
	lock, err := acquireIPQualityDependencyLock(ctx, "/run/qagent-managed-tls")
	if err != nil {
		return err
	}
	defer lock.Close()
	directory := filepath.Join(tlsFrontendRoot, "requests")
	if err := validateProtectedDirectoryChain(directory); err != nil {
		return err
	}
	path := filepath.Join(directory, name)
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 || info.Size() > 4<<20 {
		return errors.New("unsafe TLS request file")
	}
	if err = validateOwner(info, "TLS request"); err != nil {
		return err
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var request tlsFrontendRequest
	if err = json.Unmarshal(data, &request); err != nil {
		return err
	}
	engine, _, ok := managedSpecForService(request.Service, request.Kind)
	if !ok || engine != core.EngineSingBox {
		return errors.New("TLS request must target a standard managed sing-box service")
	}
	services, err := NewServiceManager(request.Kind)
	if err != nil {
		return err
	}
	if err = services.validate(); err != nil {
		return err
	}
	manager := tlsFrontendManager{tlsFrontendRoot, tlsFrontendState, services, NewCoreUpdater()}
	for _, f := range request.Frontends {
		if err = f.Validate(); err != nil {
			return err
		}
	}
	if request.Stage {
		return manager.stage(ctx, request.Service, request.Frontends)
	}
	return manager.apply(ctx, request.Service, request.Frontends, request.Action)
}

func (e *Executor) executeTLSFrontend(ctx context.Context, spec EngineSpec, task core.Task, stage bool) error {
	if task.Engine != core.EngineSingBox {
		if len(task.TLSFrontends) > 0 {
			return errors.New("managed TLS requires sing-box")
		}
		return nil
	}
	if len(task.TLSFrontends) == 0 {
		if _, err := os.Stat(filepath.Join(tlsFrontendRoot, "deployments.json")); errors.Is(err, os.ErrNotExist) {
			return nil
		}
	}
	engine, _, ok := managedSpecForService(spec.Service, e.serviceManager().Kind())
	if !ok || engine != task.Engine {
		return errors.New("托管 TLS 需要标准面板管理的 sing-box 服务")
	}
	directory := filepath.Join(tlsFrontendRoot, "requests")
	if err := os.MkdirAll(directory, 0700); err != nil {
		return err
	}
	if err := validateProtectedDirectoryChain(directory); err != nil {
		return err
	}
	suffix, err := randomSuffix(12)
	if err != nil {
		return err
	}
	name := suffix + ".json"
	request := tlsFrontendRequest{spec.Service, e.serviceManager().Kind(), task.Action, stage, task.TLSFrontends}
	encoded, err := json.Marshal(request)
	if err != nil {
		return err
	}
	if _, err = atomicDeploy(filepath.Join(directory, name), string(encoded)); err != nil {
		return err
	}
	defer os.Remove(filepath.Join(directory, name))
	if e.serviceManager().Kind() == ServiceManagerOpenRC {
		return RunTLSFrontendRequest(ctx, name)
	}
	executable, err := os.Executable()
	if err != nil {
		return err
	}
	executable, err = ipQualityExecutable(executable)
	if err != nil {
		return err
	}
	runner, err := ipQualityExecutable("/usr/bin/systemd-run")
	if err != nil {
		return err
	}
	unit := "qagent-tls-prepare-" + suffix + ".service"
	args := tlsFrontendHelperArguments(executable, unit, name)
	// The same fixed helper sandbox supports package installation and service
	// setup without broadening the long-running Agent's mount permissions.
	output, runErr := runIPQualityCommand(ctx, runner, args)
	cleanup, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	_, _ = run(cleanup, e.serviceManager().executable, "stop", unit)
	if runErr != nil {
		return fmt.Errorf("托管 TLS 操作失败：%w；%s", runErr, output)
	}
	return nil
}

func tlsFrontendHelperArguments(executable, unit, name string) []string {
	args := ipQualityDependencyHelperArguments(executable, unit)
	args = args[:len(args)-1]
	return append(args, "manage-tls", name)
}

func managedTLSStateExists() bool {
	_, err := os.Stat(filepath.Join(tlsFrontendRoot, "deployments.json"))
	return err == nil
}

func stopServiceTLSFrontends(ctx context.Context, manager *ServiceManager, engine core.Engine, spec EngineSpec) error {
	if engine != core.EngineSingBox || !managedTLSStateExists() {
		return nil
	}
	executor := &Executor{Services: manager}
	return executor.executeTLSFrontend(ctx, spec, core.Task{Engine: engine, Action: core.ActionStop}, false)
}
