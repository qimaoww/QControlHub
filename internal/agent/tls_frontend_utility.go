type tlsFrontendRequest struct {
	Service      string                         `json:"service"`
	Kind         string                         `json:"kind"`
	Action       core.Action                    `json:"action"`
	Stage        bool                           `json:"stage"`
	Frontends    []core.TLSFrontend             `json:"frontends"`
	Certificates bool                           `json:"certificates,omitempty"`
	Deadline     time.Time                      `json:"deadline,omitempty"`
	SyncSource   *core.ManagedCertificateSource `json:"sync_source,omitempty"`
}

var tlsRequestName = regexp.MustCompile(`^[a-f0-9]{24}\.json$`)

// StateDirectory is writable even for older Agent units whose /etc mount is
// read-only. Only the fixed privileged helper writes TLS service configuration.
const tlsFrontendRequests = "/var/lib/qcontrolhub/tls-requests"

// RunTLSFrontendRequest is a fixed local helper. Request files are root-owned,
// private, and generated by the Agent; service identities are restricted to
// the panel's standard managed core base service and shared instances.
func RunTLSFrontendRequest(ctx context.Context, name string) error {
	if !tlsRequestName.MatchString(name) {
		return errors.New("invalid TLS request name")
	}
	directory := tlsFrontendRequests
	if err := validateProtectedDirectoryChain(directory); err != nil {
		return err
	}
	path := filepath.Join(directory, name)
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 || info.Size() > 4<<20 {
		return errors.New("unsafe TLS request file")
	}
	if err = validateOwner(info, "TLS request"); err != nil {
		return err
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var request tlsFrontendRequest
	if err = json.Unmarshal(data, &request); err != nil {
		return err
	}
	engine, _, ok := managedSpecForService(request.Service, request.Kind)
	if !ok || engine != core.EngineSingBox && engine != core.EngineXray {
		return errors.New("TLS request must target a standard managed Xray or sing-box service")
	}
	services, err := NewServiceManager(request.Kind)
	if err != nil {
		return err
	}
	if err = services.validate(); err != nil {
		return err
	}
	manager := tlsFrontendManager{tlsFrontendRoot, tlsFrontendState, services, NewCoreUpdater()}
	if request.SyncSource != nil {
		source := *request.SyncSource
		spec, err := managedCertificateSpec(source, request.Kind)
		if err != nil || source.Engine != engine || spec.Service != request.Service {
			return errors.New("invalid managed certificate service")
		}
		report := manager.scanManagedCertificate(source, request.Kind)
		encoded, err := json.Marshal(report)
		if err != nil {
			return errors.New("cannot encode managed certificate response")
		}
		_, err = atomicDeploy(filepath.Join(directory, name+".result"), string(encoded))
		return err
	}
	lock, err := acquireIPQualityDependencyLock(ctx, "/run/qagent-managed-tls")
	if err != nil {
		return err
	}
	defer lock.Close()
	for _, f := range request.Frontends {
		if (engine == core.EngineXray) != (f.Transport == "xhttp") {
			return errors.New("TLS frontend transport does not belong to this managed core")
		}
		if err = f.Validate(); err != nil {
			return err
		}
	}
	if !request.Deadline.IsZero() {
		var cancel context.CancelFunc
		ctx, cancel = context.WithDeadline(ctx, request.Deadline)
		defer cancel()
	}
	if request.Action == core.ActionStatus {
		return manager.repairRuntime(ctx)
	}
	if request.Certificates {
		return manager.prepareStagedCertificates(ctx, request.Service, request.Frontends)
	}
	if request.Stage {
		return manager.stage(ctx, request.Service, request.Frontends)
	}
	return manager.apply(ctx, request.Service, request.Frontends, request.Action)
}

func (e *Executor) executeTLSFrontend(ctx context.Context, spec EngineSpec, task core.Task, stage bool, reports ...*strings.Builder) error {
	return e.executeTLSFrontendRequest(ctx, spec, task, stage, false, reports...)
}

func (e *Executor) executeTLSFrontendRequest(ctx context.Context, spec EngineSpec, task core.Task, stage, certificates bool, reports ...*strings.Builder) error {
	if task.Engine != core.EngineSingBox && task.Engine != core.EngineXray {
		if len(task.TLSFrontends) > 0 {
			return errors.New("managed TLS requires Xray or sing-box")
		}
		return nil
	}
	if len(task.TLSFrontends) == 0 {
		if _, err := os.Stat(filepath.Join(tlsFrontendRoot, "deployments.json")); errors.Is(err, os.ErrNotExist) {
			return nil
		}
	}
	engine, _, ok := managedSpecForService(spec.Service, e.serviceManager().Kind())
	if !ok || engine != task.Engine {
		return errors.New("托管 TLS 需要标准面板管理的 Xray / sing-box 服务")
	}
	name, err := writeTLSFrontendRequest(tlsFrontendRequest{Service: spec.Service, Kind: e.serviceManager().Kind(), Action: task.Action, Stage: stage, Frontends: task.TLSFrontends, Deadline: tlsOperationDeadline(ctx), Certificates: certificates})
	if err != nil {
		return err
	}
	defer os.Remove(filepath.Join(tlsFrontendRequests, name))
	executable, err := os.Executable()
	if err != nil {
		return err
	}
	executable, err = ipQualityExecutable(executable)
	if err != nil {
		return err
	}
	helperCtx, helperCancel := context.WithDeadline(context.WithoutCancel(ctx), tlsOperationDeadline(ctx).Add(40*time.Second))
	defer helperCancel()
	if e.serviceManager().Kind() == ServiceManagerOpenRC {
		output, err := runIPQualityCommand(helperCtx, executable, []string{"manage-tls", name})
		if len(reports) > 0 {
			reports[0].WriteString(output)
		}
		if err != nil {
			return fmt.Errorf("托管 TLS 操作失败：%w；%s", err, output)
		}
		return nil
	}
	runner, err := ipQualityExecutable("/usr/bin/systemd-run")
	if err != nil {
		return err
	}
	unit := "qagent-tls-prepare-" + strings.TrimSuffix(name, ".json") + ".service"
	args := tlsFrontendHelperArguments(executable, unit, name)
	// The same fixed helper sandbox supports package installation and service
	// setup without broadening the long-running Agent's mount permissions.
	output, runErr := runIPQualityCommand(helperCtx, runner, args)
	cleanup, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	_, _ = run(cleanup, e.serviceManager().executable, "stop", unit)
	if len(reports) > 0 {
		reports[0].WriteString(output)
	}
	if runErr != nil {
		return fmt.Errorf("托管 TLS 操作失败：%w；%s", runErr, output)
	}
	return nil
}

func writeTLSFrontendRequest(request tlsFrontendRequest) (string, error) {
	directory := tlsFrontendRequests
	if err := os.MkdirAll(directory, 0700); err != nil {
		return "", err
	}
	if err := validateProtectedDirectoryChain(directory); err != nil {
		return "", err
	}
	suffix, err := randomSuffix(12)
	if err != nil {
		return "", err
	}
	name := suffix + ".json"
	encoded, err := json.Marshal(request)
	if err != nil {
		return "", err
	}
	if _, err = atomicDeploy(filepath.Join(directory, name), string(encoded)); err != nil {
		return "", err
	}
	return name, nil
}

func tlsFrontendHelperArguments(executable, unit, name string) []string {
	args := ipQualityDependencyHelperArguments(executable, unit)
	args = args[:len(args)-1]
	for index, value := range args {
		if strings.HasPrefix(value, "--property=RuntimeMaxSec=") {
			args[index] = "--property=RuntimeMaxSec=405s"
		}
	}
	return append(args, "manage-tls", name)
}

func managedTLSStateExists() bool {
	_, err := os.Stat(filepath.Join(tlsFrontendRoot, "deployments.json"))
	return err == nil
}

func stopServiceTLSFrontends(ctx context.Context, manager *ServiceManager, engine core.Engine, spec EngineSpec) error {
	if engine != core.EngineSingBox && engine != core.EngineXray || !managedTLSStateExists() {
		return nil
	}
	executor := &Executor{Services: manager}
	return executor.executeTLSFrontend(ctx, spec, core.Task{Engine: engine, Action: core.ActionStop}, false)
}

func tlsOperationDeadline(ctx context.Context) time.Time {
	deadline := time.Now().Add(core.ManagedTLSOperationTimeout)
	if parent, ok := ctx.Deadline(); ok && parent.Before(deadline) {
		return parent
	}
	return deadline
}
