async (page) => {
  const base = '__BASE__', stage = '__STAGE__', theme = '__THEME__', device = '__DEVICE__';
  const root = '/root/.codex/worktrees/7d05/qcontrolhub/docs/ui-review-20261018/evidence';
  const viewport = device === 'mobile' ? {width:390,height:844} : device === 'tablet' ? {width:820,height:1180} : {width:1440,height:1000};
  await page.setViewportSize(viewport);
  await page.emulateMedia({colorScheme:theme,reducedMotion:'reduce'});
  await page.addInitScript(theme => {localStorage.setItem('qcontrolhub-color-theme',theme);},theme);
  const results=[];
  const open = async kind => {
    await page.goto(`${base}/?kind=${kind}`);
    await page.waitForSelector('html[data-review-ready="true"]');
    await page.waitForSelector(kind==='xhttp'||kind==='tls'?'#server-plan-form':'.workspace-main');
    await page.evaluate(async theme=>{localStorage.setItem('qcontrolhub-color-theme',theme);const {createShellAppearance}=await import('/assets/modules/shell-appearance.js');createShellAppearance({data:{}}).applyTheme(theme);},theme);
  };
  const shot=async name=>{
    await page.screenshot({path:`${root}/${stage}-${device}-${theme}-${name}.png`,fullPage:false});
    results.push({name,viewport,theme,actualTheme:await page.evaluate(()=>document.documentElement.dataset.theme),touch:await page.evaluate(()=>({points:navigator.maxTouchPoints,coarse:matchMedia("(pointer:coarse)").matches})),overflow:await page.evaluate(()=>({width:innerWidth,document:document.documentElement.scrollWidth,dialogs:[...document.querySelectorAll('dialog[open]')].map(d=>({width:d.clientWidth,scrollWidth:d.scrollWidth,height:d.clientHeight,scrollHeight:d.scrollHeight}))}))});
  };
  const close=async()=>{await page.locator('dialog[open] [data-cert-close]').first().click();};
  await open('certificates');
  await page.locator('[data-cert-create]').waitFor();
  await shot('certificates');
  await page.locator('[data-cert-detail="review-cert"]').click();
  await page.locator('[data-cert-share]').waitFor();
  await shot('certificate-detail');
  await page.locator('[data-cert-share]').click();
  await page.locator('[data-cert-grant-form]').waitFor();
  await shot('certificate-grants'); await close();
  await page.locator('[data-cert-detail="review-dns"]').click();
  await page.locator('[data-cert-continue]').waitFor();
  await shot('certificate-dns-order'); await close();
  await page.locator('[data-cert-sources]').click();
  await page.locator('[data-cert-source-action]').first().waitFor();
  await shot('certificate-sources'); await close();
  await page.locator('[data-cert-accounts]').click();
  await page.locator('[data-cert-new-account]').waitFor();
  await shot('certificate-accounts');
  await page.locator('[data-cert-new-account]').click();
  await page.locator('[data-cert-account-form]').waitFor();
  await shot('certificate-acme-account'); await close();
  await page.locator('[data-cert-accounts]').click();
  await page.locator('[data-cert-new-dns]').click();
  await page.locator('[data-cert-account-form]').waitFor();
  await shot('certificate-dns-account'); await close();
  await page.locator('[data-cert-create]').click();
  await page.locator('[data-cert-form]').waitFor();
  await shot('certificate-create');
  await page.locator('[name=method]').selectOption('http-01');
  await page.locator('[name=agent_id]').waitFor();
  await page.locator('[name=agent_id]').selectOption('bravo');
  await shot('certificate-http');
  await page.locator('[name=source]').selectOption('import');
  await page.locator('[name=certificate]').waitFor();
  await shot('certificate-import'); await close();
  await page.evaluate(()=>window.reviewEmpty=true);
  await page.locator('[data-cert-refresh]').click();
  await page.locator('[data-cert-detail]').first().waitFor({state:'detached'});
  await shot('certificate-empty');
  await open('traffic');
  await page.locator('[data-traffic-sync]').click();
  await page.locator('[data-sync-choice]').first().waitFor();
  await shot('traffic-sync');
  await open('sharing');
  await page.evaluate(()=>{location.hash='#settings-node-alpha';});
  await page.locator('[data-node-tab="agent"]').click();
  await page.locator('[data-agent-sharing]').click();
  await page.locator('[name=http_domains]').waitFor();
  await shot('node-sharing');
  await open('tls');
  await page.locator('[data-tls-advanced]').evaluate(e=>e.open=true);
  await shot('tls-preset');
  await open('xhttp');
  await page.locator('.xhttp-options').evaluateAll(es=>es.forEach(e=>e.open=true));
  await shot('xhttp-preset');
  await open('settings');
  await page.locator('[name=acme_email]').waitFor();
  await page.locator('#settings-certificates').scrollIntoViewIfNeeded();
  await shot('settings-acme');
  return {stage,device,theme,results};
}
