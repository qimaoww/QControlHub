async (page) => {
  const base='__BASE__', device='__DEVICE__', theme='__THEME__';
  const root='/root/.codex/worktrees/7d05/qcontrolhub/docs/ui-review-20261018/evidence';
  const results=[];
  const check=(value,label)=>{if(!value)throw Error(label);results.push(label);};
  const viewport=device==='mobile'?{width:390,height:844}:device==='tablet'?{width:820,height:1180}:{width:1440,height:1000};
  await page.setViewportSize(viewport);
  await page.emulateMedia({colorScheme:theme,reducedMotion:'reduce'});
  await page.addInitScript(t=>localStorage.setItem('qcontrolhub-color-theme',t),theme);
  await page.goto(base+'/?kind=certificates');
  await page.locator('[data-cert-create]').waitFor();
  await page.evaluate(async t=>{const {createShellAppearance}=await import('/assets/modules/shell-appearance.js');createShellAppearance({data:{}}).applyTheme(t);},theme);
  check(await page.evaluate(()=>document.documentElement.dataset.theme)===theme,'requested theme is active');
  await page.locator('[data-cert-create]').click();
  await page.locator('[name=name]').fill('同一份草稿');
  await page.locator('[name=domains]').fill('*.example.test');
  await page.locator('[name=method]').selectOption('http-01');
  await page.locator('[name=agent_id]').waitFor();
  check(await page.locator('[name=name]').inputValue()==='同一份草稿','method switch retains draft');
  check(await page.locator('[name=domains]').evaluate(e=>!e.checkValidity()),'HTTP-01 validates restored wildcard domains');
  await page.locator('[name=domains]').fill('edge.example.test');
  await page.locator('[name=agent_id]').selectOption('bravo');
  check(await page.locator('[name=domains]').evaluate(e=>e.checkValidity()),'HTTP-01 accepts exact domain');
  check(await page.locator('[name=agent_id] option[value=charlie]').evaluate(e=>e.disabled),'offline node remains disabled');
  await page.locator('[data-cert-open-accounts]').click();
  await page.locator('[data-cert-return-draft]').click();
  check(await page.locator('[name=name]').inputValue()==='同一份草稿'&&await page.locator('[name=agent_id]').inputValue()==='bravo','account management returns to complete draft');
  check((await page.locator('[data-cert-node-scope]').textContent()).includes('edge.example.test'),'restored node updates authorized domain scope');
  await page.locator('[name=source]').selectOption('self-signed');
  check(await page.locator('[name=days]').getAttribute('max')==='825','self-signed validity constraint retained');
  await page.locator('[name=source]').selectOption('import');
  await page.locator('[name=certificate]').fill('-----BEGIN CERTIFICATE-----\nfixture\n-----END CERTIFICATE-----');
  await page.locator('[name=private_key]').fill('-----BEGIN PRIVATE KEY-----\nfixture\n-----END PRIVATE KEY-----');
  const dialog=page.locator('dialog[open]');
  const first=dialog.locator('button').first(), last=dialog.locator('button').last();
  await last.focus(); await page.keyboard.press('Tab');
  check(await first.evaluate(e=>e===document.activeElement),'Tab stays inside modal');
  await page.keyboard.press('Shift+Tab');
  check(await last.evaluate(e=>e===document.activeElement),'Shift+Tab stays inside modal');
  await page.locator('[data-cert-file=certificate]').setInputFiles({name:'oversize.pem',mimeType:'application/x-pem-file',buffer:Buffer.from('x'.repeat(256*1024+1))});
  check(await page.locator('[data-cert-form-error]').isVisible(),'oversized PEM error remains visible');
  await page.locator('[data-cert-file=certificate]').setInputFiles({name:'certificate-chain.pem',mimeType:'application/x-pem-file',buffer:Buffer.from('-----BEGIN CERTIFICATE-----\nfixture-file\n-----END CERTIFICATE-----')});
  await page.waitForFunction(()=>document.querySelector('[name=certificate]').value.includes('fixture-file')&&document.querySelector('[data-cert-file-name=certificate]').textContent==='certificate-chain.pem');
  check((await page.locator('[name=certificate]').inputValue()).includes('fixture-file'),'file input imports PEM content');
  check((await page.locator('[data-cert-file-name=certificate]').textContent())==='certificate-chain.pem','selected filename is visible');
  await page.evaluate(()=>{window.reviewMutationGate=new Promise(resolve=>window.releaseReviewMutation=resolve);window.reviewFailure='域名验证失败：request_id='+'x'.repeat(240)+'。'+'无法访问验证节点，确认域名解析后重试。'.repeat(12);});
  await page.locator('[data-cert-form] button[type=button]').first().scrollIntoViewIfNeeded();
  await page.locator('[data-cert-form]').locator('button').last().click();
  check(await page.locator('[data-cert-form] button').last().isDisabled(),'submission disables action while pending');
  await page.screenshot({path:`${root}/after-${device}-${theme}-certificate-pending.png`});
  await page.evaluate(()=>window.releaseReviewMutation());
  await page.locator('[data-cert-form-error]:not([hidden])').waitFor();
  check(await page.locator('[data-cert-form-error]').evaluate(e=>e===document.activeElement),'server error receives focus');
  check(await page.locator('[name=certificate]').inputValue()!=='','failed submission retains PEM input');
  check(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth+1),'long server error wraps inside modal');
  const scroll=dialog.locator('[data-cert-modal-content]');
  await scroll.hover(); await page.mouse.wheel(0,1500);
  await page.waitForTimeout(160);
  await page.locator('[data-cert-form] button').last().scrollIntoViewIfNeeded();
  check(await page.locator('[data-cert-form] button').last().evaluate(e=>{const r=e.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight;}),'submit remains reachable by scrolling');
  await page.screenshot({path:`${root}/after-${device}-${theme}-certificate-error.png`});
  await page.locator('[data-cert-close]').first().click();
  check(await page.locator('[data-cert-create]').evaluate(e=>e===document.activeElement),'closing modal restores trigger focus');
  await page.locator('[data-cert-search]').fill('no-match');
  await page.locator('[data-cert-search]').press('Tab');
  await page.locator('.user-share-empty').waitFor();
  check(await page.locator('[data-cert-detail]').count()===0,'search filter renders empty state');
  await page.evaluate(()=>{window.reviewLocked=true;});
  await page.locator('[data-cert-refresh]').click();
  await page.waitForFunction(()=>document.querySelector('[data-cert-create]')?.disabled);
  check(await page.locator('[data-cert-create]').isDisabled(),'encryption requirement still disables creation');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'page has no horizontal overflow');
  await page.screenshot({path:`${root}/after-${device}-${theme}-certificate-disabled.png`});
  if ((device==='desktop'&&theme==='dark') || (device==='mobile'&&theme==='light')) {
    await page.goto(base+'/?kind=traffic');
    await page.locator('[data-traffic-sync]').waitFor();
    await page.evaluate(()=>window.reviewTrafficFailure='读取端口失败：'+ 'diagnostic-id-'.repeat(32));
    await page.locator('[data-traffic-sync]').click();
    await page.locator('[data-sync-error]:not([hidden])').waitFor();
    check(await page.locator('dialog[open]').evaluate(e=>e.scrollWidth<=e.clientWidth+1),'long traffic error wraps inside modal');
    await page.screenshot({path:`${root}/after-${device}-${theme}-traffic-error.png`});
  }
  return {device,theme,results};
}
