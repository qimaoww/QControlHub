import assert from "node:assert/strict";
import { createConnectionCache } from "../modules/client-connection-cache.js";
import { connectionQuery, defaultConnectionFilters } from "../modules/client-connection-model.js";

// View/read lifecycle coverage lives in browser/connection-read-lifecycle.mjs.
export async function run() {
    let now = Date.parse("2026-09-21T08:00:00Z");
    const filters = defaultConnectionFilters(now);
    const first = { id: 1, agent_id: "alpha", agent_name: "Alpha", engine: "xray", client_ip: "8.8.8.8", endpoints: [{ local_port: 443 }], location: { country_code: "CN", province: "广东" } };
    const cache = createConnectionCache({ now: () => now, maxEntries: 2, maxBytes: 3000 });
    first.first_seen = first.last_seen = new Date(now).toISOString();
    const result = { records: [first], sources: [], timeline: [], ips: 1, flows: 1 };
    cache.set("a", result); cache.set("b", result); cache.get("a"); cache.set("c", result);
    assert.equal(cache.get("b"), null, "least recently used result is evicted");
    assert.ok(cache.get("a"));
    cache.set("large", { text: "x".repeat(2000) });
    assert.equal(cache.get("large"), null, "oversized payload is not retained");
    now += 301_000;
    assert.ok(cache.get("a"), "five-minute age does not expire same-day snapshots");
    now += 86400_000;
    assert.equal(cache.get("a"), null, "a snapshot outside its retention limit expires");
    now = Date.parse("2026-09-21T08:00:00Z");
    const scoped = createConnectionCache({ now: () => now });
    scoped.set(connectionQuery(filters).toString(), result);
    const countryQuery = connectionQuery({ ...filters, country_code: "CN" });
    const countryPreview = scoped.preview(countryQuery);
    assert.equal(countryPreview.records.length, 1);
    assert.equal(countryPreview.preview, true);
    assert.equal(countryPreview.ips, undefined, "country preview must not invent complete totals");
    assert.equal(scoped.preview(connectionQuery({ ...filters, country_code: "US" })), null, "country preview exposed a different region");
    const countryCache = createConnectionCache({ now: () => now });
    countryCache.set(countryQuery.toString(), result);
    assert.equal(countryCache.get(connectionQuery({ ...filters, country_code: "US" }).toString()), null);
    assert.equal(countryCache.preview(connectionQuery(filters)), null, "a country subset cannot impersonate all regions");
    countryCache.clear();
    countryCache.set(connectionQuery(filters).toString(), { ...result, records: [{ ...first, location: {} }, { ...first, location: { country_code: "CN", non_public: true } }] });
    assert.equal(countryCache.preview(countryQuery), null, "unknown and non-public rows cannot match a country");
    assert.equal(scoped.preview(connectionQuery({ ...filters, date: "2026-09-19" })), null, "different time windows never share preview data");
    assert.equal(scoped.preview(connectionQuery({ ...filters, include_non_public: "true" })), null, "source ranges never share preview data");
    assert.equal(scoped.preview(connectionQuery(filters, "", ["bravo", "alpha"])), null, "a different node order cannot reuse a page preview");
    assert.equal(scoped.get(connectionQuery(filters).toString()).fresh, true);
    now += 31000;
    assert.equal(scoped.get(connectionQuery(filters).toString()).fresh, false, "matching snapshots become stale after 30 seconds");
    assert.equal(scoped.preview(connectionQuery(filters, 'page-2')), null, "a first-page preview must not impersonate a cursor page");
    scoped.clear();
    assert.equal(scoped.get(connectionQuery(filters).toString()), null, "authorization invalidation clears retained snapshots");
    const historical = createConnectionCache({ now: () => now });
    const closed = connectionQuery({ ...filters, date: "2026-09-20" }).toString();
    now = +new Date("2026-09-21T23:59:50");
    historical.set(closed, result);
    now += 45_000;
    assert.equal(historical.get(closed).fresh, true, "closed history survives a change of day");
    now += 24 * 60 * 60_000;
    assert.equal(historical.get(closed), null, "expired history is no longer restorable");
    const disabled = createConnectionCache({ database: Promise.resolve(null) });
    disabled.bind("scope"); disabled.set("page", result); await disabled.flush();
    assert.ok(disabled.get("page"), "storage failure keeps the memory/API fallback working");
    console.log("Connection cache freshness, LRU, byte bounds and preview isolation passed");
}
