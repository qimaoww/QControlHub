import assert from "node:assert/strict";
import { createConnectionCache } from "../modules/client-connection-cache.js";
import { connectionQuery, defaultConnectionFilters } from "../modules/client-connection-model.js";

// View/read lifecycle coverage lives in browser/connection-read-lifecycle.mjs.
export async function run() {
    let now = Date.parse("2026-09-21T08:00:00Z");
    const filters = defaultConnectionFilters(now);
    const first = { id: 1, agent_id: "alpha", agent_name: "Alpha", engine: "xray", client_ip: "8.8.8.8", endpoints: [{ local_port: 443 }], location: { country_code: "CN", province: "广东" } };
    const cache = createConnectionCache({ now: () => now, maxEntries: 2, maxBytes: 1500 });
    first.first_seen = first.last_seen = new Date(now).toISOString();
    const result = { records: [first], sources: [], timeline: [], ips: 1, flows: 1 };
    cache.set("a", result); cache.set("b", result); cache.get("a"); cache.set("c", result);
    assert.equal(cache.get("b"), null, "least recently used result is evicted");
    assert.ok(cache.get("a"));
    cache.set("large", { text: "x".repeat(2000) });
    assert.equal(cache.get("large"), null, "oversized payload is not retained");
    now += 301_000;
    assert.equal(cache.get("a"), null, "old snapshots expire");
    const scoped = createConnectionCache({ now: () => now });
    scoped.set(connectionQuery(filters).toString(), result);
    assert.equal(scoped.preview(connectionQuery({ ...filters, date: "2026-09-19" })), null, "different time windows never share preview data");
    assert.equal(scoped.preview(connectionQuery({ ...filters, include_non_public: "true" })), null, "source ranges never share preview data");
    assert.equal(scoped.preview(connectionQuery(filters, "", ["bravo", "alpha"])), null, "a different node order cannot reuse a page preview");
    assert.equal(scoped.get(connectionQuery(filters).toString()).fresh, true);
    now += 31000;
    assert.equal(scoped.get(connectionQuery(filters).toString()).fresh, false, "matching snapshots become stale after 30 seconds");
    assert.equal(scoped.preview(connectionQuery(filters, 'page-2')), null, "a first-page preview must not impersonate a cursor page");
    scoped.clear();
    assert.equal(scoped.get(connectionQuery(filters).toString()), null, "authorization invalidation clears retained snapshots");
    const storage = { getItem(key) { return this[key] ?? null; }, setItem(key, value) { this[key] = value; }, removeItem(key) { delete this[key]; } };
    const persisted = createConnectionCache({ now: () => now, storage });
    persisted.bind("verified-login-scope");
    persisted.set("page", result); persisted.flush();
    now += 1000;
    const restored = createConnectionCache({ now: () => now, storage });
    assert.equal(restored.get("page"), null, "stored rows are unavailable before server verification");
    restored.restore("verified-login-scope");
    const originalTime = restored.get("page").at;
    assert.deepEqual(restored.get("page").result, result);
    now += 30_000;
    assert.equal(restored.get("page").fresh, false, "restore and hits do not renew freshness");
    restored.set("page", result, originalTime, true); restored.flush();
    restored.restore("verified-login-scope");
    assert.equal(restored.get("page").at, originalTime, "geography cannot renew data age");
    const other = createConnectionCache({ now: () => now, storage }); other.restore("another-login-scope");
    assert.equal(other.get("page"), null, "a changed login/authority cannot restore IP history");
    persisted.set("page", result); persisted.flush();
    now += 300_000;
    const expired = createConnectionCache({ now: () => now, storage }); expired.restore("verified-login-scope");
    assert.equal(expired.get("page"), null, "retention is enforced on document restoration");
    storage.setItem("qcontrolhub:connections:v1:index", '{"version":999}');
    expired.restore("verified-login-scope"); assert.equal(expired.hasStored(), false, "incompatible formats are discarded");
    storage.setItem("qcontrolhub:connections:v1:index", '{');
    expired.restore("verified-login-scope"); assert.equal(expired.hasStored(), false, "corrupt storage cannot break startup");
    const disabled = createConnectionCache({ storage: { getItem() { throw new Error("disabled"); }, setItem() { throw new Error("quota"); } } });
    assert.equal(disabled.hasStored(), false); disabled.bind("scope"); disabled.set("page", result); disabled.flush();
    assert.ok(disabled.get("page"), "storage failure keeps the memory/API fallback working");
    console.log("Connection cache TTL, LRU, byte bounds and preview isolation passed");
}
