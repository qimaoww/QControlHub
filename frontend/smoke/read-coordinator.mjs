import assert from 'node:assert/strict';
import { createReadCoordinator, readsAffectedByWrite } from '../modules/read-coordinator.js';

export async function run() {
  const deferred = () => { let resolve, reject; const promise = new Promise((yes, no) => { resolve = yes; reject = no; }); return { promise, resolve, reject }; };
  const tick = () => new Promise(setImmediate);
  const calls = [];
  const reader = createReadCoordinator((path, options) => {
    const gate = deferred(); calls.push({ path, options, ...gate }); return gate.promise;
  }, { timeout: 200, capacity: 3 });
  const a = new AbortController(), b = new AbortController();
  const first = reader.read('/agents', { signal: a.signal });
  const second = reader.read('/agents', { signal: b.signal });
  await tick(); assert.equal(calls.length, 1);
  a.abort(); await assert.rejects(first, { name: 'AbortError' });
  assert.equal(calls[0].options.signal.aborted, false, 'one reader cannot cancel another');
  calls[0].resolve([{ id: 'node' }]); assert.deepEqual(await second, [{ id: 'node' }]);
  await tick(); assert.equal(reader.size(), 0);
  const completed = reader.read('/sequence'); await tick();
  const immediate = completed.then(() => reader.read('/sequence'));
  calls.at(-1).resolve('first'); await tick();
  assert.equal(calls.at(-1).path, '/sequence'); calls.at(-1).resolve('second');
  assert.equal(await immediate, 'second', 'completion must detach before notifying callers'); await tick();
  calls.splice(1, 2);
  const x = reader.read('/agents'), y = reader.read('/agents');
  await tick(); calls[1].resolve([{ id: 'node', metrics: {} }]);
  const [left, right] = await Promise.all([x, y]); left[0].metrics.changed = true;
  assert.equal(right[0].metrics.changed, undefined, 'shared mutable responses are isolated');
  await tick();
  const old = reader.read('/agents'); await tick();
  const fresh = reader.read('/agents', { fresh: true }); await tick();
  const follower = reader.read('/agents');
  assert.equal(calls.length, 4);
  calls[3].resolve(['new']); assert.deepEqual(await fresh, ['new']); assert.deepEqual(await follower, ['new']);
  calls[2].resolve(['old']); assert.deepEqual(await old, ['old']);
  await tick();
  const invalid = reader.read('/agents'); await tick();
  const rejected = assert.rejects(invalid, { name: 'AbortError' });
  reader.invalidate(readsAffectedByWrite('/agents/node'));
  await rejected;
  const newer = reader.read('/agents'); await tick(); calls.at(-1).resolve(['current']);
  assert.deepEqual(await newer, ['current']); calls.at(-2).resolve(['late']); await tick();
  assert.equal(reader.size(), 0, 'late canceled completion cannot retain pending state');
  const fail = reader.read('/tasks?limit=50'); await tick();
  calls.at(-1).reject(new Error('offline')); await assert.rejects(fail, /offline/); await tick();
  const retry = reader.read('/tasks?limit=50'); await tick(); calls.at(-1).resolve([]); await retry; await tick();
  const hang = reader.read('/agents'); await assert.rejects(hang, /读取超时/); await tick();
  assert.equal(calls.at(-1).options.signal.aborted, true);
  assert.equal(reader.size(), 0, 'timeout releases even transports ignoring abort');
  const isolated = ['/tasks?id=1', '/tasks?id=2', '/tasks?id=3'].map(path => reader.read(path));
  await assert.rejects(reader.read('/extra'), /读取请求过多/);
  const clears = isolated.map(promise => assert.rejects(promise, { name: 'AbortError' }));
  reader.clear(); await Promise.all(clears); assert.equal(reader.size(), 0);
  const detached = new AbortController(); detached.abort();
  await assert.rejects(reader.read('/agents', { signal: detached.signal }), { name: 'AbortError' });
  const options = { conditional: { etag: 'exact', value: [] } };
  const windows = [reader.read('/core-logs?limit=200', options), reader.read('/core-logs?limit=200', options)];
  await tick(); assert.notEqual(calls.at(-1), calls.at(-2));
  calls.at(-1).resolve([]); calls.at(-2).resolve([]); await Promise.all(windows); await tick();
  assert.equal(reader.size(), 0);
  assert.equal(readsAffectedByWrite('/preferences/node-order')('/agents'), false);
  assert.equal(readsAffectedByWrite('/preferences/node-order')('/preferences/node-order'), true);
  assert.equal(readsAffectedByWrite('/tasks')('/tasks/other?view=status'), false);
  assert.equal(readsAffectedByWrite('/tasks/one/retry')('/tasks/one'), true);
  console.log('Read coordination: isolation, cancellation, fresh overlap, invalidation, recovery and capacity passed');
}
