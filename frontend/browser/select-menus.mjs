import { reconcileView } from '../modules/refresh.js';
import { installSelectMenus } from '../modules/select-menu.js';
import { assert, waitFor } from './assertions.mjs';

export async function testSelectMenusRuntime() {
  document.body.innerHTML = `<main class="workspace-main"><form><label class="settings-field">服务<select name="service" required><option value="">请选择</option><option value="alpha">Alpha</option><option value="disabled" disabled>Disabled</option><optgroup label="离线" disabled><option value="offline">Offline</option></optgroup><optgroup label="地区"><option value="beta">Beta</option><option value="gamma">Gamma</option></optgroup><option value="hidden" hidden>Hidden</option></select></label><button type="submit">保存</button></form><button data-outside>其他操作</button><dialog class="user-allocation-dialog"><label class="settings-field">节点<select name="node"></select></label></dialog></main>`;
  installSelectMenus();
  const form = document.querySelector('form'), select = form.elements.service;
  const popup = () => document.querySelector('[role=listbox][popover]');
  const key = value => select.dispatchEvent(new KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true }));
  const paint = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  let inputs = 0, changes = 0, submits = 0;
  select.addEventListener('input', () => inputs++);
  select.addEventListener('change', () => changes++);
  form.addEventListener('submit', event => { event.preventDefault(); submits++; });
  assert.ok(!form.checkValidity(), 'empty required select must remain invalid');
  const fresh = form.cloneNode(true);
  select.click();
  reconcileView(form, fresh);
  await Promise.resolve();
  assert.ok(popup() && select.getAttribute('aria-expanded') === 'true', 'native dropdown did not open themed menu');
  assert.equal(document.activeElement, select, 'opening moved keyboard focus away from the native control');
  assert.equal(popup().querySelectorAll('[role=option]').length, 6, 'hidden option was exposed');
  assert.equal(popup().querySelectorAll('[role=option]:disabled').length, 2, 'disabled option/group became selectable');
  key('ArrowDown'); key('ArrowDown');
  assert.ok(select.getAttribute('aria-activedescendant').endsWith('-4'), 'arrow key did not skip disabled options and groups');
  key('Escape');
  assert.ok(!popup() && select.value === '' && changes === 0, 'Escape committed a tentative selection');
  select.click(); key('b'); key('Enter');
  assert.equal(select.value, 'beta', 'typeahead selection failed');
  assert.ok(inputs === 1 && changes === 1, 'selection must emit input/change exactly once');
  assert.equal(new FormData(form).get('service'), 'beta', 'native form value was not preserved');
  form.requestSubmit();
  assert.equal(submits, 1, 'themed control blocked a valid submission');
  select.click(); popup().querySelector('[data-select-index="4"]').click();
  assert.ok(changes === 1 && !popup(), 'reselecting the same value emitted a change');
  select.click(); key('End'); key('Tab');
  assert.equal(select.value, 'gamma', 'Tab did not accept keyboard selection');
  form.reset();
  assert.ok(select.value === '' && !popup() && !form.checkValidity(), 'form reset or required validation changed');
  select.disabled = true; select.click();
  assert.ok(!popup(), 'disabled control opened a menu');
  select.disabled = false; select.click();
  select.options[1].disabled = true;
  await waitFor(() => !popup(), 'menu retained obsolete options after a dynamic update');
  select.click(); document.querySelector('[data-outside]').click();
  document.querySelector('[data-outside]').dispatchEvent(new PointerEvent('pointerdown', {bubbles:true}));
  assert.ok(!popup(), 'outside pointer did not dismiss the menu');
  select.click(); select.remove();
  await waitFor(() => !popup(), 'route removal leaked a menu');

  const dialog = document.querySelector('dialog'), node = dialog.querySelector('select');
  for (let i = 0; i < 100; i++) node.add(new Option(`节点 ${i} ${'长名称'.repeat(12)}`, String(i)));
  const spacer = document.createElement('section');
  spacer.innerHTML = '<p>滚动后的弹窗定位</p>'.repeat(80);
  document.body.append(spacer);
  window.scrollTo({ top: 400, behavior: 'instant' });
  await paint();
  assert.ok(scrollY > 0, 'scroll regression did not establish a scrolled page');
  dialog.showModal();
  for (const theme of ['light', 'dark']) {
    document.documentElement.dataset.theme = theme;
    node.click();
    await paint();
    const menu = popup(), bounds = menu.getBoundingClientRect();
    assert.ok(menu.matches(':popover-open'), 'options are not in the top layer over the modal');
    assert.ok(dialog.contains(menu), 'options became inert outside the modal');
    assert.ok(bounds.left >= -1 && bounds.right <= innerWidth + 1 && bounds.top >= -1 && bounds.bottom <= innerHeight + 1, `${theme}: dropdown overflows viewport`);
    assert.ok(menu.scrollHeight > menu.clientHeight, 'long option list is not scrollable');
    const expected = getComputedStyle(document.documentElement).getPropertyValue('--surface').trim();
    assert.ok(getComputedStyle(menu).backgroundColor !== 'rgba(0, 0, 0, 0)' && expected, `${theme}: menu lost theme surface`);
    node.dispatchEvent(new KeyboardEvent('keydown', {key:'End', bubbles:true, cancelable:true}));
    assert.ok(menu.scrollTop > 0, 'keyboard selection did not scroll into view');
    node.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape', bubbles:true, cancelable:true}));
    assert.ok(dialog.open && !popup() && node.value === '0', 'Escape changed the value or closed its parent dialog');
  }
  node.click(); dialog.close();
  spacer.remove();
  assert.ok(!popup(), 'closing the dialog leaked options');

  form.insertAdjacentHTML('beforeend', '<label>域名<input name="domain" list="domains" required><datalist id="domains"><option value="alpha.example.test"><option value="beta.example.test"></datalist></label>');
  const domain = form.elements.domain;
  domain.focus();
  domain.click();
  assert.ok(popup() && !domain.hasAttribute('list'), 'datalist retained the native suggestion popup');
  const freshInput = domain.cloneNode(true);
  freshInput.setAttribute('list', 'domains');
  reconcileView(domain, freshInput);
  await Promise.resolve();
  assert.ok(popup() && !domain.hasAttribute('list'), 'refresh restored the native suggestion popup');
  domain.value = 'beta';
  domain.dispatchEvent(new Event('input', {bubbles:true}));
  assert.equal(popup().querySelectorAll('[role=option]').length, 1, 'domain suggestions did not filter');
  domain.dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowDown', bubbles:true, cancelable:true}));
  domain.dispatchEvent(new KeyboardEvent('keydown', {key:'Enter', bubbles:true, cancelable:true}));
  assert.equal(domain.value, 'beta.example.test', 'domain suggestion did not commit');
  domain.value = 'custom.example.test';
  domain.dispatchEvent(new Event('input', {bubbles:true}));
  assert.ok(!popup() && domain.value === 'custom.example.test', 'suggestions restricted free text');
  domain.value = ''; domain.dispatchEvent(new Event('input', {bubbles:true}));
  domain.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape', bubbles:true, cancelable:true}));
  assert.ok(!popup() && domain.value === '', 'Escape changed domain text');
  document.querySelector('[data-outside]').focus();
  assert.equal(domain.getAttribute('list'), 'domains', 'blur did not restore the native datalist binding');
  assert.ok(!domain.hasAttribute('role'), 'blur leaked authored combobox attributes');
}
