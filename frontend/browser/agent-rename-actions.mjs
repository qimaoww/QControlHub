import { assert, waitFor, delay } from './assertions.mjs';
import { startNativeNodes } from './agent-detail-actions.mjs';

export async function testAgentRenameActions({ testAPI, onlineAgent, populatedAgents }) {
  testAPI.agents = [onlineAgent('alpha'), onlineAgent('bravo')];
  await startNativeNodes();
  const button = (text, root = document) => [...root.querySelectorAll('button')].find(item => item.textContent === text);
  button('查看设置', document.querySelector('[data-agent-id=alpha]')).click();
  const box = await waitFor(() => document.querySelector('dialog[open] input[name=name]')?.closest('dialog'), '改名设置未打开');
  const form = box.querySelector('input[name=name]').form, input = form.elements.name;
  const submit = form.querySelector('[type=submit]');
  const writes = () => testAPI.calls.filter(call => call.method === 'PUT' && call.path === '/agents/alpha/name').length;
  const idle = () => waitFor(() => !document.querySelector('#app[aria-busy=true]'), '改名未结束');
  const before = writes();
  input.value = '   '; form.requestSubmit(); await idle(); assert.equal(writes(), before, '空白名称提交');
  input.value = '香港 & Tokyo <edge>'; testAPI.renameFailure = true; form.requestSubmit();
  await waitFor(() => form.textContent.includes('服务暂不可用') && !submit.disabled, '改名失败未反馈或解锁');
  assert.equal(input.value, '香港 & Tokyo <edge>', '改名失败丢失输入');
  testAPI.renameFailure = false; form.requestSubmit();
  await waitFor(() => box.querySelector('h2').textContent.includes('香港 & Tokyo <edge>'), '改名后标题未更新');
  await idle(); assert.equal(box.querySelector('h2 edge'), null, '节点名称未转义');
  assert.equal(input.value, '香港 & Tokyo <edge>', '改名后输入错误');
  button('刷新', document.querySelector('.a-top')).click(); await delay(30);
  assert.ok(box.querySelector('h2').textContent.includes('香港 & Tokyo <edge>'), '刷新覆盖自定义名称');
  let release; testAPI.renameGate = new Promise(resolve => { release = resolve; });
  input.value = '正在保存的名称'; const pending = writes(); form.requestSubmit();
  await waitFor(() => writes() === pending + 1, '改名请求未发出');
  input.value = '保存期间继续编辑的名称'; form.requestSubmit();
  assert.equal(writes(), pending + 1, '改名重复提交');
  release(); testAPI.renameGate = null;
  await waitFor(() => box.querySelector('h2').textContent.includes('正在保存的名称'), '延迟改名未完成'); await idle();
  assert.equal(input.value, '保存期间继续编辑的名称', '迟到保存覆盖新输入');
  testAPI.agents = testAPI.agents.filter(agent => agent.id !== 'alpha');
  button('刷新', document.querySelector('.a-top')).click();
  await waitFor(() => !box.isConnected && !document.querySelector('[data-agent-id=alpha]'), '节点移除后仍保留详情或操作');
  location.hash = '#settings-node-unknown';
  await waitFor(() => document.querySelector('dialog[open]')?.textContent.includes('节点不存在'), '未知节点路由缺少权限或缺失提示');
  assert.ok(!document.querySelector('dialog[open] input[name=name]'), '未知节点保留改名表单');
  document.querySelector('dialog[open] [aria-label=关闭]').click(); await delay(20);
  location.hash = '#settings-node-bravo';
  const remaining = await waitFor(() => document.querySelector('dialog[open] input[name=name]')?.closest('dialog'), '剩余节点未加载');
  assert.ok(!button('查看安装命令', remaining), '无命令的节点提供了恢复入口');
  testAPI.agents = populatedAgents.map(agent => structuredClone(agent));
}
