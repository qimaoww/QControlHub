  const nameBox=form.elements.name.getBoundingClientRect(),addressBox=form.elements.address.getBoundingClientRect();
  assert.ok(addressBox.top>=nameBox.bottom,'field hint overlaps address input');
  form.elements.name.value='香港 & ATT <edge>';
  testAPI.profileSaveFailure=true;form.requestSubmit();
  await waitFor(()=>form.querySelector('.a-notice')?.textContent&&!form.querySelector('[type=submit]').disabled,'failed save did not recover');
