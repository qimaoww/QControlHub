  assert.equal(testAPI.profileSaves.length,calls+1,'duplicate save requests');
  release();testAPI.profileSaveGate=null;await saved();
  assert.equal(name(20001),'香港 & ATT <edge>','first port name not updated');
  assert.equal(row(20001).querySelector('edge'),null,'name not escaped');
  assert.equal(name(20002),'ss-rust-2','rename changed second port');
  assert.equal('address' in testAPI.profileSaves.at(-1),false,'rename fixed automatic address');
  assert.equal('address_mode' in testAPI.profileSaves.at(-1),false,'rename changed protocol stack');
