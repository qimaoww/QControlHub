  versionForm.elements.release_channel.value='custom';versionForm.elements.release_channel.dispatchEvent(new Event('change',{bubbles:true}));
  versionForm.elements.custom_version.value='1.14.0-draft';
  runtime(true,'1.13.1');await waitFor(()=>card()?.dataset.coreInstalled==='1','settings installation did not refresh');
