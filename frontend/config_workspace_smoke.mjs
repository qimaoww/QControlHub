import assert from "node:assert/strict";
import {createConfigDocument} from "./modules/config-document.js";
import {createConfigWorkspaceState} from "./modules/config-workspace-state.js";
import {configSourceProblem} from "./modules/config-source-editor.js";
import {setStorageAccount} from "./modules/account-storage.js";

const native = '{\n "future": 18446744073709551615,\n "inbounds": [{"tag":"first","protocol":"socks","port":1080,"unknown":9007199254740993}, {"tag":"second","protocol":"http","port":8080}],\n "outbounds": [{"tag":"direct","protocol":"freedom"}, {"tag":"fallback","protocol":"blackhole"}],\n "routing":{"rules":[]}\n}\n';
const model = createConfigDocument("xray", native);
assert.equal(model.content(), native, "opening/saving an untouched document must retain its exact bytes");
assert.equal(model.dirty(), false);
const first = model.objects().find(item => item.tag === "first").id;
model.select(first);
model.edit(model.text().replace('"port":1080', '"port":1081'));
const changed = model.content();
assert.ok(changed.includes('"future": 18446744073709551615'));
assert.ok(changed.includes('"unknown":9007199254740993'));
assert.ok(changed.includes('{"tag":"second","protocol":"http","port":8080}'));
assert.ok(changed.includes('[{"tag":"direct","protocol":"freedom"}, {"tag":"fallback","protocol":"blackhole"}]'), "default outbound priority and unedited tokens must survive section changes");
model.select("source");
assert.equal(model.text(), changed);
const custom = changed.replace('"future": 18446744073709551615', '"future": {"id":18446744073709551615,"enabled":true}');
model.edit(custom);
model.select(first);
assert.ok(model.text().includes('"port":1081'), "full source and section forms must consume the same edited object");
model.select("source");
assert.equal(model.text(), custom, "switching source modes cannot reformat custom content");
model.edit('{"inbounds":');
assert.throws(() => model.content());
assert.equal(model.text(), '{"inbounds":', "invalid source remains editable");
const broken = model.snapshot();
const recovered = createConfigDocument("xray", native, broken);
assert.equal(recovered.text(), '{"inbounds":');
assert.equal(recovered.dirty(), true);
recovered.edit(custom);
assert.equal(recovered.content(), custom);
recovered.replace('{"outbounds":[{"tag":"own","protocol":"freedom","limit":9007199254740993}],"inbounds":[]}');
assert.equal(recovered.objects().filter(item => item.kind === "inbound").length, 0, "deleting objects in complete source updates navigation/counts");
assert.equal(recovered.objects().find(item => item.kind === "outbound").tag, "own");
assert.equal(recovered.selected(), "source");
recovered.reset();
assert.equal(recovered.content(), native);
assert.equal(recovered.dirty(), false);
const identities = createConfigDocument("xray", native);
const originalIds = identities.objects().filter(item => item.kind === "inbound").map(item => item.id);
identities.select("source");
identities.edit(native.replace('"tag":"first"', '"tag":"renamed"'));
assert.equal(identities.objects().find(item => item.tag === "renamed").id, originalIds[0], "renaming an object retains its selection identity");
const snapshot = identities.snapshot();
const restoredIds = createConfigDocument("xray", native, snapshot);
restoredIds.edit(snapshot.source.replace('"inbounds": [', '"inbounds": [{"tag":"new","protocol":"socks","port":9090},'));
const ids = restoredIds.objects().map(item => item.id);
assert.equal(new Set(ids).size, ids.length, "new objects after reload cannot reuse restored identities");
const referenced = createConfigDocument("sing-box", '{"custom":"first","inbounds":[{"tag":"first","type":"socks","listen_port":1080}],"outbounds":[{"tag":"direct","type":"direct"}],"route":{"rules":[{"inbound":["first"],"outbound":"direct"}],"final":"direct"}}');
referenced.select(referenced.objects().find(item => item.tag === "first").id);
referenced.edit(referenced.text().replace('"first"', '"renamed"'));
let referenceDocument = JSON.parse(referenced.content());
assert.deepEqual(referenceDocument.route.rules[0].inbound, ["renamed"]);
assert.equal(referenceDocument.custom, "first", "renaming must not rewrite unknown fields with similar text");
referenced.select(referenced.objects().find(item => item.tag === "direct").id);
referenced.edit(referenced.text().replace('"direct"', '"exit"'));
referenceDocument = JSON.parse(referenced.content());
assert.equal(referenceDocument.route.final, "exit");
assert.equal(referenceDocument.route.rules[0].outbound, "exit");
const collision = createConfigDocument("sing-box", '{"custom":{"detour":"first"},"outbounds":[{"tag":"first","type":"direct"},{"tag":"second","type":"direct"}],"route":{"final":"first"}}');
collision.select(collision.objects().find(item => item.tag === "first").id);
collision.edit(collision.text().replace('"first"', '"second"'));
assert.throws(() => collision.content(), /已被其他对象使用/, "ambiguous tag edits must retain the draft instead of rebinding references");
collision.edit(collision.text().replace('"second"', '"renamed"'));
const collisionContent = JSON.parse(collision.content());
assert.equal(collisionContent.route.final, "renamed");
assert.equal(collisionContent.custom.detour, "first", "native reference updates cannot rewrite unknown objects");

for (const [engine, content] of [["mihomo", "# custom comment\nlisteners: []\nfuture: &shared {id: 18446744073709551615}\ncopy: *shared\n"], ["ss-rust", '{"servers":[],"future":18446744073709551615}\n']]) {
  const doc = createConfigDocument(engine, content);
  doc.edit(content + "\n");
  doc.select("preview");
  assert.equal(doc.text(), content + "\n");
  doc.select("common");
  assert.equal(doc.content(), content + "\n", "native comments, aliases and numeric tokens must survive view switches");
}
assert.equal(createConfigDocument("xray", "").dirty(), false, "loading an empty workspace must never create an unsaved draft");
assert.match(configSourceProblem("xray", '{"inbounds":[{"type":"socks","listen_port":1080}]}'), /sing-box/);
assert.match(configSourceProblem("sing-box", '{"inbounds":[{"protocol":"socks","port":1080}]}'), /Xray/);
assert.equal(configSourceProblem("xray", native), "");

const previous = globalThis.sessionStorage;
const storage = new Map();
globalThis.sessionStorage = {getItem:key => storage.get(key) ?? null, setItem:(key, value) => storage.set(key, value), removeItem:key => storage.delete(key)};
try {
  const session = {role:"user", user_id:"workspace-alice"};
  const state = {session, data:{}, route:"live-config", navigationEpoch:1, routeSignal:new AbortController().signal};
  setStorageAccount(session);
  const registry = createConfigWorkspaceState({state});
  const old = registry.begin(), latest = registry.begin();
  assert.equal(old.current(), false, "out-of-order workspace reads must expire");
  assert.equal(latest.current(), true);
  const context = {agentId:"shared-node", engine:"xray", sourceMode:"personal", content:native, saved:{id:"own", version:4, content:native}};
  let record = registry.open(context);
  record.document.select("source"); record.document.edit(custom);
  const node2 = registry.open({...context, agentId:"other-node"});
  assert.equal(node2.document.dirty(), false);
  record = registry.open(context);
  assert.equal(record.document.text(), custom, "returning to a node retains that node's draft");
  const reloaded = createConfigWorkspaceState({state:{...state, data:{}}});
  const restored = reloaded.open(context);
  assert.equal(restored.document.text(), custom, "browser reload restores a draft without writing the server");
  assert.equal(restored.conflict, false);
  const conflict = createConfigWorkspaceState({state:{...state, data:{}}}).open({...context, saved:{...context.saved, version:5}});
  assert.equal(conflict.conflict, true);
  assert.equal(conflict.document.text(), custom, "a newer server revision must not destroy an old draft");
  const imported = registry.open({...context, sourceMode:"import"});
  assert.equal(imported.document.dirty(), false, "system snapshots never inherit personal drafts");
  state.navigationEpoch++;
  assert.equal(latest.current(), false);
  state.session = {role:"user", user_id:"workspace-bob"}; state.data = {};
  setStorageAccount(state.session);
  const bob = registry.open(context);
  assert.equal(bob.document.content(), native);
  assert.equal(bob.document.dirty(), false, "a shared node cannot leak another account's draft");
  assert.equal(storage.size, 0);
  setStorageAccount(null);
  registry.clear(); reloaded.clear();
} finally {
  if (previous === undefined) delete globalThis.sessionStorage;
  else globalThis.sessionStorage = previous;
}
console.log("Configuration document: complete/section source, precision, native comments, draft reload, races and account isolation passed");
