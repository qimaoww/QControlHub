import assert from "node:assert/strict";
import { createPermissionChecker } from "./modules/permissions.js";
import { coreInstallBlockReason } from "./modules/core-install-state.js";
const state = {session: {role: "user", permissions: ["tasks.execute"]}};
const can = createPermissionChecker(state);
const owner = {can_manage: true, status: "online", capabilities: ["mihomo"], supported_capabilities: ["mihomo", "xray"], features: ["preset-auto-install-v1","independent-egress-v1"], runtime: {}};
assert.equal(coreInstallBlockReason(owner, "mihomo", can), "", "tasks.read and agents.manage are separate operations");
assert.match(coreInstallBlockReason(owner, "mihomo", can, {pending:true}), /正在执行/);
assert.match(coreInstallBlockReason(owner, "xray", can), /未启用/);
assert.match(coreInstallBlockReason(owner, "ss-rust", can), /不支持/);
assert.match(coreInstallBlockReason({...owner, status:"offline"}, "mihomo", can), /离线/);
assert.match(coreInstallBlockReason({...owner, features:[]}, "mihomo", can, {automatic:true}), /Agent 不支持/);
const shared = {...owner, can_manage:false, features:[...owner.features,"shared-traffic-v1","shared-engines-v1","shared-core-instances-v1","shared-core-prepare-v1"]};
assert.equal(coreInstallBlockReason(shared, "mihomo", can), "");
assert.match(coreInstallBlockReason({...shared,runtime:{mihomo:{installed:true}}}, "mihomo", can), /复用当前版本/);
assert.equal(coreInstallBlockReason(shared, "mihomo", can, {automatic:true}), "");
assert.match(coreInstallBlockReason({...shared, features:owner.features}, "mihomo", can, {automatic:true}), /所有者升级/);
state.session.permissions = ["agents.manage", "tasks.read"];
assert.match(coreInstallBlockReason(owner, "mihomo", can), /tasks.execute/);
state.session = {role:"admin"};
assert.equal(coreInstallBlockReason(owner, "mihomo", can), "");
console.log("Core install operation permissions and state reasons passed");
